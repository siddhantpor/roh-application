-- Fresh PostgreSQL database only, matching databasepostgresql.py and the team's
-- Neon column names. No DROP statements and no seed-data resets.
-- Existing team databases: use migrate_checkin.sql (once, if needed), then
-- migrate_auth_posters.sql instead. CREATE IF NOT EXISTS does not migrate tables.
BEGIN;
CREATE TABLE IF NOT EXISTS accounts (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    auth0_sub TEXT UNIQUE,
    password TEXT,
    email TEXT,
    is_admin BOOLEAN NOT NULL DEFAULT false,
    display_name TEXT,
    approved BOOLEAN NOT NULL DEFAULT false,
    pending BOOLEAN NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_date DATE NOT NULL,
    event_starttime TIME,
    event_endtime TIME,
    event_title TEXT NOT NULL,
    event_descrip TEXT,
    event_locat TEXT,
    graphic_link TEXT,
    graphic_public_id TEXT,
    checkin_code TEXT,
    checkout_code TEXT
);
CREATE TABLE IF NOT EXISTS rsvps (
    user_id BIGINT NOT NULL REFERENCES accounts(user_id),
    event_id BIGINT NOT NULL REFERENCES events(event_id),
    accepted BOOLEAN NOT NULL,
    time TIMESTAMP NOT NULL,
    PRIMARY KEY (user_id, event_id, time)
);
CREATE TABLE IF NOT EXISTS attendance (
    user_id BIGINT NOT NULL REFERENCES accounts(user_id),
    event_id BIGINT NOT NULL REFERENCES events(event_id),
    time TIMESTAMP NOT NULL,
    approved BOOLEAN NOT NULL DEFAULT false,
    is_checkin BOOLEAN NOT NULL,
    UNIQUE (user_id, event_id, is_checkin)
);
COMMIT;
